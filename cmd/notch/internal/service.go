package internal

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
	"text/template"
)

type Service struct {
	Name       string
	Port       int    // single-image services only
	Tag        string // image tag, see ImageTag
	Postgres   bool
	Auth       bool        // Keycloak OIDC client; see scripts/app-clients.sh
	Secrets    []string    // prompted from the user; auth adds OIDC_CLIENT_SECRET itself
	Components []Component // monorepos: one container each, split by path
}

var (
	// Name becomes the namespace, Deployment and Ingress name: DNS label rules.
	dnsLabel  = regexp.MustCompile(`^[a-z0-9]([-a-z0-9]{0,61}[a-z0-9])?$`)
	envKey    = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)
	exposeRe  = regexp.MustCompile(`(?im)^\s*EXPOSE\s+(\d+)`)
	nameClean = strings.NewReplacer("_", "-", ".", "-")
)

// First match wins, so order matters when a repo has several markers.
var stackPorts = []struct {
	marker string
	port   int
}{
	{"package.json", 3000},
	{"pyproject.toml", 8000},
	{"requirements.txt", 8000},
	{"go.mod", 8080},
}

// IsRemote tells a git URL from a local path.
func IsRemote(src string) bool {
	return strings.Contains(src, "://") || strings.HasPrefix(src, "git@")
}

// NameFrom derives the service name from a repo URL or path.
func NameFrom(src string) (string, error) {
	if !IsRemote(src) {
		// Base of "." or "../" is useless; the directory's real name isn't.
		if abs, err := filepath.Abs(src); err == nil {
			src = abs
		}
	}
	base := filepath.Base(strings.TrimRight(src, "/"))
	if i := strings.LastIndex(base, ":"); i >= 0 {
		base = base[i+1:]
	}
	name := nameClean.Replace(strings.ToLower(strings.TrimSuffix(base, ".git")))
	if !dnsLabel.MatchString(name) {
		return "", fmt.Errorf("%q isn't a valid service name (lowercase letters, digits, dashes)", name)
	}
	return name, nil
}

func ValidSecretKey(k string) bool { return envKey.MatchString(k) }

// ValidName: names become namespaces and Deployments, so DNS label rules.
func ValidName(n string) bool { return dnsLabel.MatchString(n) }

// HasDockerfile decides docker build vs Railpack.
func HasDockerfile(dir string) bool {
	_, err := os.Stat(filepath.Join(dir, "Dockerfile"))
	return err == nil
}

// DetectPort reads EXPOSE from the Dockerfile, else guesses from the stack.
func DetectPort(dir string) (int, error) {
	if df, err := os.ReadFile(filepath.Join(dir, "Dockerfile")); err == nil {
		if m := exposeRe.FindSubmatch(df); m != nil {
			return strconv.Atoi(string(m[1]))
		}
	}
	for _, s := range stackPorts {
		if _, err := os.Stat(filepath.Join(dir, s.marker)); err == nil {
			return s.port, nil
		}
	}
	return 8080, nil
}

