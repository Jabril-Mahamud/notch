package internal

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
	"text/template"
)

type Service struct {
	Name     string
	Port     int
	Postgres bool
	Secrets  []string
}

var (
	// Name becomes the namespace, Deployment and Ingress name: DNS label rules.
	dnsLabel  = regexp.MustCompile(`^[a-z0-9]([-a-z0-9]{0,61}[a-z0-9])?$`)
	envKey    = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)
	exposeRe  = regexp.MustCompile(`(?im)^\s*EXPOSE\s+(\d+)`)
	nameClean = strings.NewReplacer("_", "-", ".", "-")
)

// First match wins, so order matters when a repo has several markers.
var stackPorts = []struct {
	marker string
	port   int
}{
	{"package.json", 3000},
	{"pyproject.toml", 8000},
	{"requirements.txt", 8000},
	{"go.mod", 8080},
}

// IsRemote tells a git URL from a local path.
func IsRemote(src string) bool {
	return strings.Contains(src, "://") || strings.HasPrefix(src, "git@")
}

// NameFrom derives the service name from a repo URL or path.
func NameFrom(src string) (string, error) {
	if !IsRemote(src) {
		// Base of "." or "../" is useless; the directory's real name isn't.
		if abs, err := filepath.Abs(src); err == nil {
			src = abs
		}
	}
	base := filepath.Base(strings.TrimRight(src, "/"))
	if i := strings.LastIndex(base, ":"); i >= 0 {
		base = base[i+1:]
	}
	name := nameClean.Replace(strings.ToLower(strings.TrimSuffix(base, ".git")))
	if !dnsLabel.MatchString(name) {
		return "", fmt.Errorf("%q isn't a valid service name (lowercase letters, digits, dashes)", name)
	}
	return name, nil
}

func ValidSecretKey(k string) bool { return envKey.MatchString(k) }

// DetectPort reads EXPOSE from the Dockerfile, else guesses from the stack.
func DetectPort(dir string) (int, error) {
	df, err := os.ReadFile(filepath.Join(dir, "Dockerfile"))
	if err != nil {
		return 0, fmt.Errorf("no Dockerfile in %s: notch builds every service from one", dir)
	}
	if m := exposeRe.FindSubmatch(df); m != nil {
		return strconv.Atoi(string(m[1]))
	}
	for _, s := range stackPorts {
		if _, err := os.Stat(filepath.Join(dir, s.marker)); err == nil {
			return s.port, nil
		}
	}
	return 8080, nil
}

var serviceTmpl = template.Must(template.New("service").Parse(`# Generated by notch add.
service:
  name: {{.Name}}
  ports:
    - name: http
      port: {{.Port}}
  deployment:
    containers:
      app: {}
{{- if .Postgres}}
  postgres: true
{{- end}}
{{- if .Secrets}}
  secrets:
{{- range .Secrets}}
    - {{.}}
{{- end}}
{{- end}}
`))

// Host keeps the :8080 Kind port mapping; the chart strips it for the Ingress.
var valuesTmpl = template.Must(template.New("values").Parse(`service:
  endpoints:
    internal:
      hosts:
        - {{.Name}}.notch.localhost:8080
  deployment:
    containers:
      app:
        image:
          ref: {{.Name}}:local
`))

// WriteService creates services/<name>/{service.yaml,local/values.yaml}.
func WriteService(root string, s Service) (string, error) {
	dir := filepath.Join(root, "services", s.Name)
	if _, err := os.Stat(dir); err == nil {
		return "", fmt.Errorf("%s already exists", dir)
	}
	if err := os.MkdirAll(filepath.Join(dir, "local"), 0o755); err != nil {
		return "", err
	}
	if err := render(filepath.Join(dir, "service.yaml"), serviceTmpl, s); err != nil {
		return "", err
	}
	return dir, render(filepath.Join(dir, "local", "values.yaml"), valuesTmpl, s)
}

func render(path string, t *template.Template, s Service) error {
	f, err := os.Create(path)
	if err != nil {
		return err
	}
	defer f.Close()
	return t.Execute(f, s)
}

// OnDev fails unless the repo is on dev, the branch ArgoCD watches.
func OnDev(root string) error {
	branch, err := Output("git", "-C", root, "branch", "--show-current")
	if err != nil {
		return err
	}
	if branch != "dev" {
		return fmt.Errorf("on branch %q: notch commits to dev, check it out first", branch)
	}
	return nil
}

// Publish commits path (relative to root) to dev and pushes it.
func Publish(root, path, msg string) error {
	if err := RunIn(root, "git", "add", path); err != nil {
		return err
	}
	if err := RunIn(root, "git", "commit", "-m", msg); err != nil {
		return err
	}
	return RunIn(root, "git", "push", "origin", "dev")
}
