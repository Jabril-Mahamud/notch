// Staging only overrides the host: image refs come from local/values.yaml on
// main, so promotion ships exactly what dev ran.
var stagingTmpl = template.Must(template.New("staging").Parse(`service:
  endpoints:
    internal:
      hosts:
        - {{.Name}}.staging.notch.localhost:8443
`))

// WriteService creates services/<name>/{service.yaml,local/,staging/values.yaml}.
func WriteService(root string, s Service) (string, error) {
	dir := filepath.Join(root, "services", s.Name)
	if _, err := os.Stat(dir); err == nil {
		return "", fmt.Errorf("%s already exists", dir)
	}
	for _, env := range []string{"local", "staging"} {
		if err := os.MkdirAll(filepath.Join(dir, env), 0o755); err != nil {
			return "", err
		}
	}
	if err := render(filepath.Join(dir, "staging", "values.yaml"), stagingTmpl, s); err != nil {
		return "", err
	}
	if err := render(filepath.Join(dir, "service.yaml"), serviceTmpl, s); err != nil {
		return "", err
	}
	return dir, render(filepath.Join(dir, "local", "values.yaml"), valuesTmpl, s)
}

func render(path string, t *template.Template, s Service) error {
	f, err := os.Create(path)
	if err != nil {
		return err
	}
	defer f.Close()
	return t.Execute(f, s)
}

// OnDev fails unless the repo is on dev, the branch ArgoCD watches.
func OnDev(root string) error {
	branch, err := Output("git", "-C", root, "branch", "--show-current")
	if err != nil {
		return err
	}
	if branch != "dev" {
		return fmt.Errorf("on branch %q: notch commits to dev, check it out first", branch)
	}
	return nil
}

// Publish commits path (relative to root) to dev and pushes it.
func Publish(root, path, msg string) error {
	if err := RunIn(root, "git", "add", path); err != nil {
		return err
	}
	if err := RunIn(root, "git", "commit", "-m", msg); err != nil {
		return err
	}
	return RunIn(root, "git", "push", "origin", "dev")
}
