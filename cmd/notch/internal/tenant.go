// WriteTenant creates tenants/<name>/platform.yaml. The chart defaults cover
// quotas, so the file only names the tenant; overrides get added by hand.
func WriteTenant(root, name string) (string, error) {
	if !dnsLabel.MatchString(name) {
		return "", fmt.Errorf("%q isn't a valid tenant name (lowercase letters, digits, dashes)", name)
	}
	dir := filepath.Join(root, "tenants", name)
	if _, err := os.Stat(dir); err == nil {
		return "", fmt.Errorf("%s already exists", dir)
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return "", err
	}
	body := fmt.Sprintf("# Generated by notch tenant create.\ntenant:\n  name: %s\n", name)
	return dir, os.WriteFile(filepath.Join(dir, "platform.yaml"), []byte(body), 0o644)
}

// WaitForTenant nudges the tenants ApplicationSet (it polls git every 3 min
// otherwise) and waits for the deployer ServiceAccount the chart creates.
func WaitForTenant(name string) error {
	_ = Kubectl("-n", "argocd", "annotate", "applicationset", "tenants",
		"argocd.argoproj.io/application-set-refresh=true", "--overwrite")
	sa := name + "-deployer"
	for deadline := time.Now().Add(5 * time.Minute); time.Now().Before(deadline); time.Sleep(5 * time.Second) {
		if exec.Command("kubectl", "--context", Context, "-n", name, "get", "sa", sa).Run() == nil {
			return nil
		}
	}
	return fmt.Errorf("serviceaccount %s/%s didn't appear in 5m: check `notch list`", name, sa)
}

// Issuer is Keycloak's notch realm; the apiserver (kind-up.sh), ArgoCD and
// Grafana all verify tokens against this exact URL.
const Issuer = "https://keycloak.notch.localhost/realms/notch"

// NotchHome holds the CA and Keycloak creds kind-up.sh generates.
func NotchHome() string {
	if h := os.Getenv("NOTCH_HOME"); h != "" {
		return h
	}
	home, _ := os.UserHomeDir()
	return filepath.Join(home, ".config", "notch")
}

// TenantKubeconfig points kubectl at the notch cluster as whoever logs in to
// Keycloak: RBAC comes from their groups (oidc:<tenant>), not a minted token.
func TenantKubeconfig(name string) (string, error) {
	server, err := KubectlOutput("config", "view", "--raw", "--minify", "-o", "jsonpath={.clusters[0].cluster.server}")
	if err != nil {
		return "", err
	}
	ca, err := KubectlOutput("config", "view", "--raw", "--minify", "-o", "jsonpath={.clusters[0].cluster.certificate-authority-data}")
	if err != nil {
		return "", err
	}
	return Kubeconfig(name, server, ca, filepath.Join(NotchHome(), "ca", "ca.crt")), nil
}

// Kubeconfig renders a single-context kubeconfig defaulting to the tenant's
// namespace. kubelogin runs the browser login and caches the token; notchCA
// verifies Keycloak's cert.
func Kubeconfig(name, server, ca, notchCA string) string {
	return fmt.Sprintf(`apiVersion: v1
kind: Config
clusters:
- name: notch
  cluster:
    server: %[2]s
    certificate-authority-data: %[3]s
users:
- name: oidc
  user:
    exec:
      apiVersion: client.authentication.k8s.io/v1
      command: kubelogin
      args:
      - get-token
      - --oidc-issuer-url=%[5]s
      - --oidc-client-id=kubernetes
      - --oidc-extra-scope=email
      - --certificate-authority=%[4]s
      interactiveMode: IfAvailable
contexts:
- name: notch-%[1]s
  context:
    cluster: notch
    user: oidc
    namespace: %[1]s
current-context: notch-%[1]s
`, name, server, ca, notchCA, Issuer)
}
